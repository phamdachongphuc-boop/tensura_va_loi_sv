    async createBattle(challenger: string, target: string, p1hp: number, p1max: number, p2hp: number, p2max: number) {
        if (!this.supabase) return false;

        // Xóa battle cũ nếu có
        await this.supabase.from('tensura_battles').delete().or(`challenger.eq.${challenger},target.eq.${challenger}`);

        const newBattle = {
            server_id: this.serverId,
            challenger,
            target,
            status: 'PENDING',
            turn: challenger,
            logs: [],
            p1_hp: p1hp, p1_max_hp: p1max,
            p2_hp: p2hp, p2_max_hp: p2max
        };

        const { error } = await this.supabase.from('tensura_battles').insert(newBattle);
        
        if (error) {
            console.error("Create Battle Error:", error);
            if (error.code === '42P01') {
                return 'MISSING_TABLE';
            }
            return false;
        }
        return true;
    }

    async performBattleAction(battle: BattleState, user: UserProfile, skillName: string, attackerStats: Character) {
        if (!this.supabase) return;

        // 1. Identify roles
        const isChallenger = user.username === battle.challenger;
        const opponentName = isChallenger ? battle.target : battle.challenger;
        
        // 2. Load Opponent Data for Defense calc (Real stats)
        const opponentData = await this.loadGameData(opponentName);
        const opponentDef = opponentData?.character.attributes.defense || 0;
        
        // 3. BASE DAMAGE LOGIC (Min 250,000)
        const MIN_DMG = 250000;
        const statDmg = (attackerStats.attributes.strength * 10) + (attackerStats.attributes.magic * 10);
        let baseDmg = Math.max(MIN_DMG, statDmg);

        // 4. SKILL TIER MULTIPLIER
        let multiplier = 1.0;
        let isUltimate = false;
        let isGenesis = false;
        
        // GOD MODE CHECK
        if (attackerStats.status.isGodMode) {
            multiplier = 10000.0; // Infinite Power Multiplier
            isGenesis = true; // Treated as Genesis Tier
        }

        // Ultimate Keywords
        if (['Raphael', 'Beelzebuth', 'Veldora', 'Uriel', 'Michael', 'Sariel', 'Metatron', 'Raguel', 'Gabriel', 'Lucifer', 'Mammon', 'Satanael', 'Leviathan', 'Belphegor', 'Asmodeus'].some(s => skillName.includes(s))) {
            multiplier = Math.max(multiplier, 5.0); // Ultimate Tier
            isUltimate = true;
        }
        
        // Genesis/God Tier Keywords (Skills stronger than Ultimate)
        if (['Hư Không', 'Azathoth', 'Cthugha', 'Sáng Thế', 'Vô Hạn', 'Bất Diệt', 'Long Thần', 'God', 'Infinity', 'Chaos', 'Void'].some(s => skillName.includes(s))) {
            multiplier = Math.max(multiplier, 10.0); // Genesis Tier
            isGenesis = true;
        }

        // Apply multiplier and defense reduction
        let damage = Math.floor((baseDmg * multiplier) - (opponentDef * 2));
        if (damage < MIN_DMG) damage = MIN_DMG; // Ensure Minimum Damage again after Defense

        // 5. EFFECT RNG SYSTEM
        // Effects: Crit (x1.5), Double (x2), Lifesteal (Heal), Stun (Skip Turn), None
        const rand = Math.random();
        let effectType = 'NORMAL';
        let effectLog = '';
        let healAmount = 0;
        let isStunned = false;

        if (rand < 0.25) {
            effectType = 'CRIT'; // 25% Bạo Kích
            damage = Math.floor(damage * 1.5);
            effectLog = '⚡ [BẠO KÍCH CHÍ MẠNG]';
        } else if (rand < 0.35) {
            effectType = 'DOUBLE'; // 10% x2 Sát Thương
            damage = damage * 2;
            effectLog = '💥 [SONG KÍCH HỦY DIỆT x2]';
        } else if (rand < 0.50) {
            effectType = 'LIFESTEAL'; // 15% Hút Máu
            healAmount = Math.floor(damage * 0.3);
            effectLog = `🩸 [HÚT MÁU] (+${healAmount.toLocaleString()} HP)`;
        } else if (rand < 0.60) {
            effectType = 'STUN'; // 10% Choáng/Tê Liệt
            isStunned = true;
            effectLog = '💫 [TÊ LIỆT - ĐỐI THỦ MẤT LƯỢT]';
        }

        // Apply Genesis Bonus (Always breaks limits)
        if (isGenesis) {
            damage = Math.floor(damage * 1.5); // Bonus 50% for Genesis
            effectLog = `🌌 [HƯ KHÔNG NGUYÊN THỦY] ${effectLog}`;
        }
        
        // God Mode Override Log
        if (attackerStats.status.isGodMode) {
            effectLog = `∞ [SỨC MẠNH VÔ CỰC] ${effectLog}`;
        }

        // 6. Update HP Values
        let newP1Hp = BigInt(battle.p1_hp);
        let newP2Hp = BigInt(battle.p2_hp);
        const p1Max = BigInt(battle.p1_max_hp);
        const p2Max = BigInt(battle.p2_max_hp);

        const dmgBig = BigInt(damage);
        const healBig = BigInt(healAmount);

        if (isChallenger) {
            // I am P1, I hit P2
            newP2Hp = newP2Hp - dmgBig;
            if (newP2Hp < 0n) newP2Hp = 0n;
            
            if (healAmount > 0) {
                newP1Hp = newP1Hp + healBig;
                if (newP1Hp > p1Max) newP1Hp = p1Max;
            }
        } else {
            // I am P2, I hit P1
            newP1Hp = newP1Hp - dmgBig;
            if (newP1Hp < 0n) newP1Hp = 0n;

            if (healAmount > 0) {
                newP2Hp = newP2Hp + healBig;
                if (newP2Hp > p2Max) newP2Hp = p2Max;
            }
        }

        // 7. Create Log
        const newLog = {
            turn: (battle.logs.length || 0) + 1,
            actor: user.username,
            skill: skillName,
            damage: damage,
            effect: effectType, // Store effect for UI
            description: `${effectLog} gây ${damage.toLocaleString()} sát thương!`
        };
        
        const updatedLogs = [...(battle.logs || []), newLog];

        // 8. Check Win or Next Turn
        if (newP1Hp <= 0n || newP2Hp <= 0n) {
            const winner = newP1Hp > 0n ? battle.challenger : battle.target;
            const loser = newP1Hp > 0n ? battle.target : battle.challenger;
            
            await this.supabase
                .from('tensura_battles')
                .update({ 
                    logs: updatedLogs, 
                    p1_hp: Number(newP1Hp), 
                    p2_hp: Number(newP2Hp) 
                })
                .eq('id', battle.id);

            await this.finishBattle(battle.id, winner, loser);
        } else {
            // Determine Next Turn
            // If Stunned, turn DOES NOT switch. Attacker goes again.
            const nextTurn = isStunned ? user.username : opponentName;

            await this.supabase
                .from('tensura_battles')
                .update({
                    p1_hp: Number(newP1Hp),
                    p2_hp: Number(newP2Hp),
                    logs: updatedLogs,
                    turn: nextTurn
                })
                .eq('id', battle.id);
        }
    }

    async checkActiveBattle(username: string): Promise<BattleState | null> {
        if (!this.supabase) return null;
        try {
            const { data, error } = await this.supabase
                .from('tensura_battles')
                .select('*')
                .eq('status', 'IN_PROGRESS')
                .or(`challenger.eq.${username},target.eq.${username}`)
                .maybeSingle();
            if (error && error.code !== 'PGRST116') throw error;
            return data as BattleState;
        } catch (e) { return null; }
    }

    async checkPendingInvite(username: string): Promise<BattleState | null> {
        if (!this.supabase) return null;
        try {
            const { data, error } = await this.supabase
                .from('tensura_battles')
                .select('*')
                .eq('status', 'PENDING')
                .eq('target', username)
                .maybeSingle();
            if (error && error.code !== 'PGRST116') throw error;
            return data as BattleState;
        } catch (e) { return null; }
    }

