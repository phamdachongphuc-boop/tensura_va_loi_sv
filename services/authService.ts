    async surrenderBattle(battleId: number, username: string) {
        if (!this.supabase) return;
        const b = await this.getBattle(battleId);
        if(!b) return;
        const winner = b.challenger === username ? b.target : b.challenger;
        await this.finishBattle(battleId, winner, username);
    }

    async finishBattle(battleId: number, winner: string, loser: string) {
        if (!this.supabase) return;

        await this.supabase
            .from('tensura_battles')
            .update({ status: 'FINISHED', winner: winner })
            .eq('id', battleId);

        const winnerDoc = await this.loadGameData(winner);
        const loserDoc = await this.loadGameData(loser);

        if (winnerDoc && winnerDoc.character && loserDoc && loserDoc.character) {
            const wChar = winnerDoc.character;
            const lChar = loserDoc.character;

            const STEAL_PERCENT = 0.3;
            const steal = (val: number) => Math.floor(val * STEAL_PERCENT);

            // Stat Steal Logic
            const stolenStr = steal(lChar.attributes.strength);
            const stolenMag = steal(lChar.attributes.magic);
            const stolenAgi = steal(lChar.attributes.agility);
            const stolenDef = steal(lChar.attributes.defense);
            
            const stolenHp = steal(lChar.status.maxHp);
            const stolenMp = steal(lChar.status.maxMp);

            wChar.attributes.strength += stolenStr;
            wChar.attributes.magic += stolenMag;
            wChar.attributes.agility += stolenAgi;
            wChar.attributes.defense += stolenDef;
            wChar.status.maxHp += stolenHp;
            wChar.status.maxMp += stolenMp;
            
            lChar.attributes.strength = Math.max(1, lChar.attributes.strength - stolenStr);
            lChar.attributes.magic = Math.max(1, lChar.attributes.magic - stolenMag);
            lChar.attributes.agility = Math.max(1, lChar.attributes.agility - stolenAgi);
            lChar.attributes.defense = Math.max(1, lChar.attributes.defense - stolenDef);
            lChar.status.maxHp = Math.max(10, lChar.status.maxHp - stolenHp);
            lChar.status.maxMp = Math.max(10, lChar.status.maxMp - stolenMp);
            
            lChar.status.hp = 1; // Loser survives with 1 HP

            await this.saveGameData(winner, winnerDoc);
            await this.saveGameData(loser, loserDoc);
        }
    }
    
